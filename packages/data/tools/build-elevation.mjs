// Builds packages/data/src/elevation.ts: a 0.1° elevation grid over the continental US (meters, Int16),
// from NOAA's ETOPO1 global relief (1 arc-minute, public domain) read through the ERDDAP service at
// CoastWatch, one request for the whole box with a stride of 6 arc-minutes. Run from the repo root:
//   node packages/data/tools/build-elevation.mjs [cached-erddap.json]
// With no argument it downloads the subset (~5.6 MB JSON); with one it reads that file.
import { readFileSync, writeFileSync } from "node:fs";
const LAT0 = 24.0, LAT1 = 49.6, LON0 = -125.0, LON1 = -66.4, STEP = 0.1;
const rows = Math.round((LAT1 - LAT0) / STEP) + 1, cols = Math.round((LON1 - LON0) / STEP) + 1;
const SOURCE = `https://coastwatch.pfeg.noaa.gov/erddap/griddap/etopo180.json?altitude%5B(${LAT0}):6:(${LAT1})%5D%5B(${LON0}):6:(${LON1})%5D`;
const src = process.argv[2];
const text = src ? readFileSync(src, "utf8") : await (await fetch(SOURCE)).text();
const t = JSON.parse(text).table;
const ci = t.columnNames.indexOf("latitude"), cj = t.columnNames.indexOf("longitude"), ca = t.columnNames.indexOf("altitude");
const data = new Int16Array(rows * cols);
let filled = 0;
for (const r of t.rows) {
  const row = Math.round((r[ci] - LAT0) / STEP), col = Math.round((r[cj] - LON0) / STEP);
  if (row < 0 || row >= rows || col < 0 || col >= cols) continue;
  const alt = Number(r[ca]);
  data[row * cols + col] = Math.max(-500, Math.min(5000, Number.isFinite(alt) ? Math.round(alt) : 0));
  filled++;
}
if (filled !== rows * cols) throw new Error(`filled ${filled} of ${rows * cols} cells`);
const b64 = Buffer.from(data.buffer).toString("base64");
const out = `// Generated by packages/data/tools/build-elevation.mjs — do not edit.
// A ${STEP}° elevation grid over the continental US in meters (Int16, row-major from the south-west
// corner; the sea below zero), from NOAA's ETOPO1 global relief model (Amante & Eakins 2009, NOAA
// NGDC, public domain) through the CoastWatch ERDDAP service.
export const ELEV_LAT0 = ${LAT0};
export const ELEV_LON0 = ${LON0};
export const ELEV_STEP = ${STEP};
export const ELEV_ROWS = ${rows};
export const ELEV_COLS = ${cols};
const B64 = "${b64}";
let grid: Int16Array | null = null;
function decode(): Int16Array {
  if (grid) return grid;
  const bin = typeof atob === "function" ? atob(B64) : Buffer.from(B64, "base64").toString("binary");
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  grid = new Int16Array(bytes.buffer);
  return grid;
}
/** Elevation in meters at a point, bilinear over the grid and never below sea level (roads run on land); 0 beyond the map. */
export function elevationAt(lat: number, lon: number): number {
  const g = decode();
  const x = (lon - ELEV_LON0) / ELEV_STEP;
  const y = (lat - ELEV_LAT0) / ELEV_STEP;
  if (x < 0 || y < 0 || x > ELEV_COLS - 1 || y > ELEV_ROWS - 1) return 0;
  const c0 = Math.floor(x), r0 = Math.floor(y);
  const c1 = Math.min(ELEV_COLS - 1, c0 + 1), r1 = Math.min(ELEV_ROWS - 1, r0 + 1);
  const fx = x - c0, fy = y - r0;
  const v = (r: number, c: number) => Math.max(0, g[r * ELEV_COLS + c]!);
  return (v(r0, c0) * (1 - fx) + v(r0, c1) * fx) * (1 - fy) + (v(r1, c0) * (1 - fx) + v(r1, c1) * fx) * fy;
}
`;
writeFileSync(new URL("../src/elevation.ts", import.meta.url), out);
console.log(`wrote elevation.ts: ${rows}×${cols}, ${(b64.length / 1024).toFixed(0)} KB base64, Denver ${data[Math.round((39.7 - LAT0) / STEP) * cols + Math.round((-105 - LON0) / STEP)]} m`);
